    private void cargarTabla(String buscar) {
        ArrayList<String[]> lista = persona.RecuperarAll(buscar);
        modelo = new DefaultTableModel();
        colums = new String[]{"COD", "Nombre y Apellido", "Cedula"};

        modelo.setColumnIdentifiers(colums);
        for (String[] aux : lista) {
            modelo.addRow(new String[]{
                aux[0],
                aux[1] + " " + aux[2] + " " + aux[3] + " " + aux[4],
                aux[5]
            });
        }
        tabla_persona.setModel(modelo);
    }

    private void Carta(String ruta) {
        try {
            tiempoViviendo = Integer.parseInt(JOptionPane.showInputDialog("Cuantos años tiene viviendo " + persona.getpNombre() + " " + persona.getpApellido() + " en la comunidad"));
            StringBuilder contenido = new StringBuilder();
            StringBuilder fecha = new StringBuilder();
            LocalDate dia = LocalDate.now();

            contenido.append("Quienes Suscriben, voceros (as), del Consejo Comunal "
                    + "“La Unión” por medio de la presente hacemos constar que el ciudadano (a) ");
            contenido.append(persona.getpNombre() + " " + persona.getsNombre() + " " + persona.getpApellido() + " " + persona.getsApellido() + "");
            contenido.append(", titular de la cedula de identidad N° " + persona.getCedula());
            System.out.println(modelos.relacionesForaneas.nDemografia());
            contenido.append(" : Esta residenciado (a) en este Sector, en la Calle: " + modelos.relacionesForaneas.nDemografia());
            if (!nCasa.equals("")) {
                contenido.append(" Casa. N° " + nCasa);
            }
            contenido.append(", desde hace aproximadamente (" + tiempoViviendo + ") años.");
            fecha.append("Constancia que se exepide a la solicitud de la parte interesada en esta ciudad de "
                    + "Altagracia de Orituco, Sector “La Union” a los " + dia.getDayOfMonth() + " dias del mes de "
                    + dia.getMonth().getDisplayName(TextStyle.FULL, Locale.forLanguageTag("es")) + " del Año " + dia.getYear());

            JasperReport archivo = JasperCompileManager.compileReport(System.getProperty("user.dir") +"/carta/carta.jrxml");
            Map dato = new HashMap<String, Object>();
            dato.put("dato", contenido);
            dato.put("fecha", fecha);
            JasperPrint prin = JasperFillManager.fillReport(archivo, dato, new JREmptyDataSource());
            JasperExportManager.exportReportToPdfFile(prin, ruta + ".pdf");
            Desktop.getDesktop().open(new File(ruta + ".pdf"));
        } catch (JRException ex) {
            System.out.println(ex);
              JOptionPane.showMessageDialog(this, ex);
        } catch (IOException ex) {
            System.out.println(ex);
            JOptionPane.showMessageDialog(this, ex);
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(null, "La entrada debe de ser numirica");
        }
    }

